#!/bin/bash
# tools/fuzz.sh - fuzz harness for the on-disk NTFS parser (GAPS.md §5.2).
#
#   tools/fuzz.sh seeds          build mkseeds, generate the seed corpus
#   tools/fuzz.sh check          deterministic corpus check (standalone
#                                runner over every seed; regression images
#                                must fail to mount cleanly; what pre-push
#                                runs)
#   tools/fuzz.sh regression     ASan+LSan run over the regression images
#                                (tools/fuzz/regression/): the leak checks
#                                the standalone cannot see; what the CI fuzz
#                                job runs before the mutation run
#   tools/fuzz.sh build          build the libFuzzer binaries (Clang only)
#   tools/fuzz.sh run [SECONDS]  mutate the corpus with libFuzzer
#                                (default 300s; 0 = until killed)
#   tools/fuzz.sh run-ro [SECONDS]  same, with the read-only-mount
#                                variant (ntfs_fuzz_ro; see below)
#
# The target is core/fuzz/fuzz_mount.c: mount a byte buffer as an NTFS
# image (read-write, with $LogFile replay, on a throwaway copy), walk it,
# read files/symlinks/xattrs. ASan+UBSan catch what the parser gets
# wrong; libFuzzer's coverage guidance is what reaches the deep branches
# a blind mutator never would.
#
# Read-only variant (stream E, GAPS.md §5.2): the same source built
# with -DNTFS_FUZZ_READONLY (ntfs_fuzz_ro / ntfs_fuzz_standalone_ro)
# opens the image read-only and mounts with NTFS_MOUNT_RDONLY and no
# replay. That reaches the driver's own geometry parse without $LogFile
# replay running first -- the path the boot-cpr regression came
# through, and one the RW target never exercises. `check` runs the RO
# standalone over the seeds too (they must mount), and over the
# regression images with per-image expectations: leak-logfile-runs
# MOUNTS read-only (the half-decoded run list is only parsed during
# replay, which RO skips), while leak-volume-label and ubsan-boot-cpr
# still fail. `regression` runs both libFuzzer binaries.
#
# Corpus: tools/fuzz/corpus/, generated, not committed (.gitignore).
# Three clean seeds from tools/fuzz/mkseeds.c (4 MiB images, dense on
# purpose -- see mkseeds.c), plus seed-dirty-log.img from
# tools/fuzz/mkdirtyseed.c: five journaled creates, snapshot while
# still mounted, so its $LogFile holds one checkpointed transaction
# and four uncheckpointed ones. libFuzzer grows the corpus: inputs
# that find new coverage are kept. A crash input worth keeping
# becomes a regression test, not a corpus blob.
#
# Crash artifacts land in tools/fuzz/crashes/ (crash-*, timeout-*, oom-*).
# A non-empty crashes/ after a run is a finding: triage it before the
# next run, and fix what it found -- a crash the fuzzer found and nobody
# fixed is worse than no fuzzer at all.
#
# Regression images (tools/fuzz/regression/, generated by
# tools/fuzz/mkregression.py from the seeds -- never committed, never
# hand-edited) are the three findings the fuzzer's first runs turned up:
# leak-volume-label.img (volume label leaked on a failed mount),
# leak-logfile-runs.img (half-decoded $LogFile run list leaked), and
# ubsan-boot-cpr.img (shift-overflow UB on a crafted boot sector).
# Each is verified non-vacuous: on the unfixed code the ASan binary
# reports the leak (55 and 192 bytes) or aborts on the UB; on the fixed
# code it exits clean. The standalone check proves they still fail to
# mount cleanly; the `regression` command proves they no longer leak
# or abort.
set -uo pipefail
. "$(dirname "$0")/env.sh"

FUZZ_DIR="$NTFS_TOOLS_DIR/fuzz"
CORPUS="$FUZZ_DIR/corpus"
REGRESSION="$FUZZ_DIR/regression"
CRASHES="$FUZZ_DIR/crashes"
FUZZ_BUILD="$NTFS_ROOT/build-fuzz"
MAX_LEN=4194304  # 4 MiB: the target rejects larger inputs outright

usage() {
	sed -n '2,/^set -uo pipefail/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'
	exit 2
}

ensure_mkseeds() {
	if [ ! -x "$FUZZ_DIR/mkseeds" ]; then
		need_tool make || return 1
		(cd "$FUZZ_DIR" && make mkseeds) || return 1
	fi
}

ensure_seeds() {
	if [ ! -f "$CORPUS/seed-basic.img" ] || [ ! -f "$CORPUS/seed-small-cluster.img" ] ||
	   [ ! -f "$CORPUS/seed-compressed.img" ]; then
		echo "==> generating seed corpus in $CORPUS"
		ensure_mkseeds || return 1
		"$FUZZ_DIR/mkseeds" -o "$CORPUS" --mkntfs "$NTFS_LOCAL/sbin/mkntfs" --force || {
			echo "seed generation failed; run 'make -C tools/fuzz seeds' for the error" >&2
			return 1
		}
	fi
	# The dirty-log seed is built by this driver, not by mkseeds
	# (libntfs-3g never writes journal records): five journaled
	# creates, snapshot while still mounted, so the $LogFile holds
	# one checkpointed transaction and four uncheckpointed ones.
	if [ ! -f "$CORPUS/seed-dirty-log.img" ]; then
		echo "==> generating dirty-log seed in $CORPUS"
		ensure_cmake || return 1
		cmake -S "$NTFS_ROOT" -B "$NTFS_ROOT/build" >/dev/null || return 1
		cmake --build "$NTFS_ROOT/build" --target mkdirtyseed -j"$(nproc 2>/dev/null || echo 4)" || return 1
		TMPDIR="${TMPDIR:-/tmp}" "$NTFS_ROOT/build/mkdirtyseed" -o "$CORPUS/seed-dirty-log.img" \
			--mkntfs "$NTFS_LOCAL/sbin/mkntfs" || {
			echo "dirty-seed generation failed" >&2
			return 1
		}
	fi
}

cmd_seeds() {
	[ -x "$NTFS_LOCAL/sbin/mkntfs" ] || { echo "mkntfs missing; run tools/build-ntfsprogs.sh first" >&2; return 1; }
	ensure_mkseeds || return 1
	"$FUZZ_DIR/mkseeds" -o "$CORPUS" --mkntfs "$NTFS_LOCAL/sbin/mkntfs" --force || return 1
	ensure_cmake || return 1
	cmake -S "$NTFS_ROOT" -B "$NTFS_ROOT/build" >/dev/null || return 1
	cmake --build "$NTFS_ROOT/build" --target mkdirtyseed -j"$(nproc 2>/dev/null || echo 4)" || return 1
	TMPDIR="${TMPDIR:-/tmp}" "$NTFS_ROOT/build/mkdirtyseed" -o "$CORPUS/seed-dirty-log.img" \
		--mkntfs "$NTFS_LOCAL/sbin/mkntfs"
}

# Deterministic corpus check: the standalone runner mounts and walks
# every seed once, and the regression images must fail to mount cleanly
# (--expect-fail: a mount that succeeds means the corruption no longer
# reaches the intended failure path). Fast (<10s after the first build)
# and no Clang needed, so pre-push can run it. Exit non-zero on any
# crash (a sanitizer abort) or missing seed. The leak half of the
# regression is NOT checked here -- the standalone has no sanitizer --
# it is checked by `regression` (ASan binary) and by the CI fuzz job.
ensure_regression() {
	mkdir -p "$REGRESSION"
	python3 "$FUZZ_DIR/mkregression.py" "$CORPUS/seed-basic.img" \
		"$REGRESSION/leak-volume-label.img" secure || return 1
	python3 "$FUZZ_DIR/mkregression.py" "$CORPUS/seed-basic.img" \
		"$REGRESSION/leak-logfile-runs.img" logfile-runs || return 1
	python3 "$FUZZ_DIR/mkregression.py" "$CORPUS/seed-basic.img" \
		"$REGRESSION/ubsan-boot-cpr.img" boot-cpr || return 1
}

cmd_check() {
	ensure_cmake || return 1
	ensure_seeds || return 1
	ensure_regression || return 1
	if [ ! -x "$NTFS_ROOT/build/ntfs_fuzz_standalone" ]; then
		echo "==> building standalone fuzz runner"
		cmake -S "$NTFS_ROOT" -B "$NTFS_ROOT/build" >/dev/null || return 1
		cmake --build "$NTFS_ROOT/build" --target ntfs_fuzz_standalone -j"$(nproc 2>/dev/null || echo 4)" || return 1
	fi
	if [ ! -x "$NTFS_ROOT/build/ntfs_fuzz_standalone_ro" ]; then
		echo "==> building read-only standalone fuzz runner"
		cmake -S "$NTFS_ROOT" -B "$NTFS_ROOT/build" >/dev/null || return 1
		cmake --build "$NTFS_ROOT/build" --target ntfs_fuzz_standalone_ro -j"$(nproc 2>/dev/null || echo 4)" || return 1
	fi
	echo "==> corpus check: $(ls "$CORPUS"/*.img | wc -l) seeds"
	# shellcheck disable=SC2086
	TMPDIR="${TMPDIR:-/tmp}" "$NTFS_ROOT/build/ntfs_fuzz_standalone" "$CORPUS"/*.img || return 1
	echo "==> corpus check (read-only): $(ls "$CORPUS"/*.img | wc -l) seeds"
	# shellcheck disable=SC2086
	TMPDIR="${TMPDIR:-/tmp}" "$NTFS_ROOT/build/ntfs_fuzz_standalone_ro" "$CORPUS"/*.img || return 1
	echo "==> regression check: $(ls "$REGRESSION"/*.img | wc -l) images (must fail to mount)"
	# shellcheck disable=SC2086
	TMPDIR="${TMPDIR:-/tmp}" "$NTFS_ROOT/build/ntfs_fuzz_standalone" --expect-fail "$REGRESSION"/*.img || return 1
	# Read-only regression expectations differ per image: the
	# logfile-runs run list is only parsed during replay, which the
	# read-only mount skips, so that image mounts read-only; the
	# other two still fail. Check each one individually.
	echo "==> regression check (read-only): per-image expectations"
	local img rc=0
	for img in "$REGRESSION"/*.img; do
		case "$(basename "$img")" in
			leak-logfile-runs.img)
				TMPDIR="${TMPDIR:-/tmp}" "$NTFS_ROOT/build/ntfs_fuzz_standalone_ro" "$img" >/dev/null 2>&1 || {
					echo "read-only regression: $img must mount, but it did not" >&2; rc=1; }
				;;
			*)
				TMPDIR="${TMPDIR:-/tmp}" "$NTFS_ROOT/build/ntfs_fuzz_standalone_ro" "$img" >/dev/null 2>&1 && {
					echo "read-only regression: $img must fail to mount, but it mounted" >&2; rc=1; }
				;;
		esac
	done
	return $rc
}

# ASan+LSan regression check: one run of each regression image through
# both libFuzzer binaries (RW and read-only). Exits 77 with a
# LeakSanitizer report if a fixed leak comes back. Needs Clang
# (cmd_build builds the binaries if absent).
cmd_regression() {
	ensure_seeds || return 1
	ensure_regression || return 1
	if [ ! -x "$FUZZ_BUILD/ntfs_fuzz" ] || [ ! -x "$FUZZ_BUILD/ntfs_fuzz_ro" ]; then
		cmd_build || return 1
	fi
	local img rc=0 bin
	for bin in "$FUZZ_BUILD/ntfs_fuzz" "$FUZZ_BUILD/ntfs_fuzz_ro"; do
		for img in "$REGRESSION"/*.img; do
			echo "==> regression: $(basename "$bin") $img"
			TMPDIR="${TMPDIR:-/tmp}" "$bin" "$img" -runs=1 || rc=1
		done
	done
	return $rc
}

cmd_build() {
	need_tool clang || { echo "fuzzing needs Clang (apt install clang)" >&2; return 1; }
	ensure_cmake || return 1
	echo "==> configuring fuzz build (CC=clang, -DNTFS_FUZZ=ON)"
	CC=clang cmake -S "$NTFS_ROOT" -B "$FUZZ_BUILD" -DNTFS_FUZZ=ON || return 1
	echo "==> building ntfs_fuzz ntfs_fuzz_ro"
	cmake --build "$FUZZ_BUILD" --target ntfs_fuzz ntfs_fuzz_ro -j"$(nproc 2>/dev/null || echo 4)" || return 1
}

cmd_run() {
	local seconds="${1:-300}" bin="${2:-$FUZZ_BUILD/ntfs_fuzz}" prefix="${3:-$CRASHES/}"
	ensure_seeds || return 1
	if [ ! -x "$bin" ]; then
		cmd_build || return 1
	fi
	mkdir -p "$CRASHES"
	echo "==> libFuzzer ($(basename "$bin")) for ${seconds}s (0 = until killed), corpus $CORPUS"
	echo "    crashes -> $CRASHES (non-empty after a run means findings)"
	TMPDIR="${TMPDIR:-/tmp}" "$bin" "$CORPUS" \
		-max_len="$MAX_LEN" -timeout=10 -max_total_time="$seconds" \
		-artifact_prefix="$prefix" -print_final_stats=1
	local rc=$?
	if [ "$rc" -ne 0 ]; then
		echo "fuzz run exited $rc -- see $CRASHES for artifacts" >&2
		return $rc
	fi
	if ls "$CRASHES"/crash-* "$CRASHES"/ro-crash-* "$CRASHES"/timeout-* "$CRASHES"/ro-timeout-* "$CRASHES"/oom-* "$CRASHES"/ro-oom-* >/dev/null 2>&1; then
		echo "findings in $CRASHES -- triage before the next run" >&2
		return 1
	fi
	echo "fuzz run clean: no crashes, timeouts, or OOMs"
	return 0
}

case "${1:-}" in
	seeds) cmd_seeds ;;
	check) cmd_check ;;
	regression) cmd_regression ;;
	build) cmd_build ;;
	run)   cmd_run "${2:-300}" ;;
	run-ro) cmd_run "${2:-300}" "$FUZZ_BUILD/ntfs_fuzz_ro" "$CRASHES/ro-" ;;
	*)     usage ;;
esac
